function generateCode(subject) {
  const s = safeString(subject).toLowerCase();
  if (s.includes('базы данных') || s.includes('база данных')) return 'VBD 3213';
  if (s.includes('python') || s.includes('питон')) return 'PYT 2214';
  if (s.includes('web') || s.includes('веб')) return 'WEB 3215';
  if (s.includes('сети') || s.includes('сеть')) return 'NET 3216';
  if (s.includes('математик')) return 'MAT 1111';
  if (s.includes('физик')) return 'PHY 1112';
  if (s.includes('химия') || s.includes('хими')) return 'CHE 1113';
  if (s.includes('биолог')) return 'BIO 1114';
  if (s.includes('история')) return 'HIS 1211';
  if (s.includes('казах')) return 'KAZ 1311';
  if (s.includes('английск') || s.includes('english')) return 'ENG 1312';
  if (s.includes('информатик')) return 'INF 2213';
  if (s.includes('программирован')) return 'PRG 2214';
  if (s.includes('алгоритм')) return 'ALG 2215';
  if (s.includes('экономик')) return 'ECO 3311';
  if (s.includes('менеджмент')) return 'MNG 3312';
  if (s.includes('безопасн')) return 'SEC 3217';
  if (s.includes('график')) return 'GRF 3218';
  
  const words = safeString(subject).trim().split(/\s+/).slice(0, 3);
  const prefix = words.map(w => (w[0] || 'X').toUpperCase()).join('').padEnd(3, 'X').substring(0, 3);
  return `${prefix} 3213`;
}


// ==================== ФУНКЦИИ ДЛЯ СОЗДАНИЯ ТЕКСТОВ И ТАБЛИЦ (АДАПТИРОВАННЫЕ ИЗ HTML-ПОДХОДА) ====================

function createTextParagraphs(text, addIndent = false) {
  const safeText = safeString(text);
  if (!safeText) return [new Paragraph({ children: [new TextRun({ text: '', size: 24 })] })];
  
  const paragraphs = [];
  const lines = safeText.split('\n');
  
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      paragraphs.push(new Paragraph({ spacing: { after: 120 } }));
      continue;
    }
    paragraphs.push(new Paragraph({
      spacing: { before: 0, after: 0 },
      indent: addIndent ? { left: 720 } : { left: 0 },
      children: [new TextRun({ text: trimmed, size: 24 })]
    }));
  }
  
  return paragraphs;
}

